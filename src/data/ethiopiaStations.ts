// Helper to quickly find any station in Ethiopia by ID
export const getEthiopiaStationById = (id: string): BusStation | undefined => {
  return ETHIOPIA_BUS_STATIONS.find((s) => s.id === id);
};

// Calculate hierarchical chain for any station
export interface InterconnectTraceResult {
  origin: BusStation;
  destination: BusStation;
  transferLegs: {
    from: BusStation;
    to: BusStation;
    tierHop: string;
    vehicleRecommendation: string;
    estDurationHours: number;
    estFareETB: number;
    highwayName: string;
  }[];
  totalEstimatedHours: number;
  totalEstimatedFareETB: number;
  totalTransfers: number;
}

export const traceInterconnectRoute = (
  fromId: string,
  toId: string
): InterconnectTraceResult | null => {
  const from = getEthiopiaStationById(fromId);
  const to = getEthiopiaStationById(toId);
  if (!from || !to) return null;

  if (from.id === to.id) {
    return {
      origin: from,
      destination: to,
      transferLegs: [],
      totalEstimatedHours: 0,
      totalEstimatedFareETB: 0,
      totalTransfers: 0,
    };
  }

  const legs: InterconnectTraceResult['transferLegs'] = [];

  // Path building logic:
  // If stations share parent or direct connection:
  const directConnected = from.connectedStationIds?.includes(to.id);

  if (directConnected) {
    const isWoreda = from.hierarchyTier === 'woreda' || to.hierarchyTier === 'woreda';
    const isFed = from.hierarchyTier === 'federal' || to.hierarchyTier === 'federal';
    legs.push({
      from,
      to,
      tierHop: `${from.hierarchyTier?.toUpperCase()} ➔ ${to.hierarchyTier?.toUpperCase()}`,
      vehicleRecommendation: isFed ? 'Luxury Express Coach (55 seats)' : isWoreda ? 'Local Minibus Dolphin / Toyota HiAce' : 'Standard Express Coaster',
      estDurationHours: 2.5,
      estFareETB: isFed ? 550 : isWoreda ? 160 : 320,
      highwayName: 'National Interconnect Highway',
    });
  } else {
    // Hierarchical multi-hop:
    // Step 1: from Woreda -> to Zonal Hub if origin is woreda
    let currentStation = from;
    if (currentStation.hierarchyTier === 'woreda' && currentStation.parentHubId) {
      const parent = getEthiopiaStationById(currentStation.parentHubId);
      if (parent) {
        legs.push({
          from: currentStation,
          to: parent,
          tierHop: 'WOREDA ➔ ZONAL HUB (የወረዳ ወደ ዞን ትስስር)',
          vehicleRecommendation: 'Local Minibus / Toyota Dolphin',
          estDurationHours: 1.2,
          estFareETB: 140,
          highwayName: 'Zonal Feeder Road',
        });
        currentStation = parent;
      }
    }

    // Step 2: If destination is in another region or needs regional/federal bridge
    // Connect to Regional Capital or Federal Gateway
    if (currentStation.id !== to.id) {
      // Connect to destination's parent if to is woreda
      const targetDestinationHub = to.hierarchyTier === 'woreda' && to.parentHubId ? getEthiopiaStationById(to.parentHubId) || to : to;

      if (currentStation.id !== targetDestinationHub.id) {
        legs.push({
          from: currentStation,
          to: targetDestinationHub,
          tierHop: `${currentStation.hierarchyTier?.toUpperCase()} ➔ ${targetDestinationHub.hierarchyTier?.toUpperCase()} (ኢንተር-ዞናል / ፌደራል ትስስር)`,
          vehicleRecommendation: 'Intercity Express Luxury Coach',
          estDurationHours: 4.5,
          estFareETB: 480,
          highwayName: 'National Trunk Highway Corridor',
        });
        currentStation = targetDestinationHub;
      }

      // Step 3: From Zonal Hub down to final Woreda if needed
      if (targetDestinationHub.id !== to.id) {
        legs.push({
          from: targetDestinationHub,
          to,
          tierHop: 'ZONAL HUB ➔ WOREDA (ከዞን ወደ መዳረሻ ወረዳ)',
          vehicleRecommendation: 'Local Minibus / Coaster Feeder',
          estDurationHours: 1.0,
          estFareETB: 120,
          highwayName: 'District Woreda Spur Road',
        });
      }
    }
  }

  const totalEstimatedHours = legs.reduce((acc, l) => acc + l.estDurationHours, 0);
  const totalEstimatedFareETB = legs.reduce((acc, l) => acc + l.estFareETB, 0);
  const totalTransfers = Math.max(0, legs.length - 1);

  return {
    origin: from,
    destination: to,
    transferLegs: legs,
    totalEstimatedHours: Number(totalEstimatedHours.toFixed(1)),
    totalEstimatedFareETB,
    totalTransfers,
  };
};
