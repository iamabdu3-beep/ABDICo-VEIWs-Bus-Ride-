// Helper to calculate realistic distance between any two stations using coordinates
export const calcStationDistanceKm = (a: BusStation, b: BusStation): number => {
  if (a.lat && a.lng && b.lat && b.lng) {
    const R = 6371; // Earth radius km
    const dLat = ((b.lat - a.lat) * Math.PI) / 180;
    const dLng = ((b.lng - a.lng) * Math.PI) / 180;
    const lat1 = (a.lat * Math.PI) / 180;
    const lat2 = (b.lat * Math.PI) / 180;
    const sinDLat = Math.sin(dLat / 2);
    const sinDLng = Math.sin(dLng / 2);
    const h = sinDLat * sinDLat + Math.cos(lat1) * Math.cos(lat2) * sinDLng * sinDLng;
    const c = 2 * Math.atan2(Math.sqrt(h), Math.sqrt(1 - h));
    const straightKm = R * c;
    // Highway curvature multiplier across Ethiopian highlands/mountains
    return Math.max(18, Math.round(straightKm * 1.28));
  }
  return 120;
};

// Helper to quickly find any station in Ethiopia by ID
export const getEthiopiaStationById = (id: string): BusStation | undefined => {
  return ETHIOPIA_BUS_STATIONS.find((s) => s.id === id);
};

// Calculate hierarchical chain for any station
export interface InterconnectTraceResult {
  origin: BusStation;
  destination: BusStation;
  transferLegs: {
    from: BusStation;
    to: BusStation;
    tierHop: string;
    vehicleRecommendation: string;
    estDurationHours: number;
    estFareETB: number;
    highwayName: string;
  }[];
  totalEstimatedHours: number;
  totalEstimatedFareETB: number;
  totalTransfers: number;
}

export const traceInterconnectRoute = (
  fromId: string,
  toId: string
): InterconnectTraceResult | null => {
  const from = getEthiopiaStationById(fromId);
  const to = getEthiopiaStationById(toId);
  if (!from || !to) return null;

  if (from.id === to.id) {
    return {
      origin: from,
      destination: to,
      transferLegs: [],
      totalEstimatedHours: 0,
      totalEstimatedFareETB: 0,
      totalTransfers: 0,
    };
  }

  const legs: InterconnectTraceResult['transferLegs'] = [];

  const createLeg = (stFrom: BusStation, stTo: BusStation, customHop?: string) => {
    const distKm = calcStationDistanceKm(stFrom, stTo);
    const isWoredaHop = stFrom.hierarchyTier === 'woreda' || stTo.hierarchyTier === 'woreda';
    const isFedHop = stFrom.hierarchyTier === 'federal' || stTo.hierarchyTier === 'federal';

    let speedKmH = isFedHop ? 62 : isWoredaHop ? 38 : 50;
    let ratePerKm = isFedHop ? 1.75 : isWoredaHop ? 1.35 : 1.55;

    const estDuration = Math.max(0.5, parseFloat((distKm / speedKmH).toFixed(1)));
    const estFare = Math.max(50, Math.round(distKm * ratePerKm));

    const defaultHop = `${stFrom.hierarchyTier?.toUpperCase()} ➔ ${stTo.hierarchyTier?.toUpperCase()}`;
    const vehicle = isFedHop
      ? 'Luxury Interstate Coach (55 Seats - Selam / Sky / Odaa)'
      : isWoredaHop
      ? 'Toyota Dolphin Minibus / Coaster Feeder (14-24 Seats)'
      : 'Standard Regional Express Coach (45 Seats)';

    const highway = isFedHop
      ? 'National Federal Trunk Highway (A-Corridor)'
      : isWoredaHop
      ? 'Zonal Feeder & Woreda Rural Road'
      : 'Inter-Regional / Inter-Zonal Asphalt Highway';

    legs.push({
      from: stFrom,
      to: stTo,
      tierHop: customHop || defaultHop,
      vehicleRecommendation: vehicle,
      estDurationHours: estDuration,
      estFareETB: estFare,
      highwayName: highway,
    });
  };

  // Direct connection check
  const directConnected = from.connectedStationIds?.includes(to.id) || to.connectedStationIds?.includes(from.id);

  if (directConnected) {
    createLeg(from, to, `DIRECT CORRIDOR (${from.hierarchyTier?.toUpperCase()} ➔ ${to.hierarchyTier?.toUpperCase()})`);
  } else {
    // Hierarchical Multi-Hop Algorithm:
    let currentStation = from;

    // Hop 1: If origin is a Woreda, connect up to its Zonal Hub (or Regional Hub)
    if (currentStation.hierarchyTier === 'woreda' && currentStation.parentHubId) {
      const parent = getEthiopiaStationById(currentStation.parentHubId);
      if (parent && parent.id !== to.id) {
        createLeg(currentStation, parent, 'WOREDA ➔ ZONAL HUB (የወረዳ ወደ ዞን መጋቢ ትስስር)');
        currentStation = parent;
      }
    }

    if (currentStation.id !== to.id) {
      // Find destination anchor hub (if destination is a Woreda, use its parent hub)
      const targetDestinationHub =
        to.hierarchyTier === 'woreda' && to.parentHubId
          ? getEthiopiaStationById(to.parentHubId) || to
          : to;

      if (currentStation.id !== targetDestinationHub.id) {
        // Cross-regional / Interstate bridge:
        // If currentStation and targetDestinationHub are in different regions and neither is Federal,
        // and destination is Addis Ababa, connect straight to Addis
        if (targetDestinationHub.hierarchyTier === 'federal' || targetDestinationHub.city === 'Addis Ababa') {
          createLeg(currentStation, targetDestinationHub, `${currentStation.hierarchyTier?.toUpperCase()} ➔ FEDERAL GATEWAY (የፌደራል ዋና መናኸሪያ)`);
          currentStation = targetDestinationHub;
        } else if (currentStation.regionName !== targetDestinationHub.regionName) {
          // Cross-region: Bridge via Regional Capital or nearest Federal Corridor
          createLeg(currentStation, targetDestinationHub, 'INTER-REGIONAL CORRIDOR (የክልሎች አቋራጭ ዋና መስመር)');
          currentStation = targetDestinationHub;
        } else {
          // Same region inter-zonal
          createLeg(currentStation, targetDestinationHub, 'INTER-ZONAL HIGHWAY (የዞኖች አገናኝ አውራ ጎዳና)');
          currentStation = targetDestinationHub;
        }
      }

      // Final Hop: From destination hub down to target Woreda if needed
      if (currentStation.id !== to.id) {
        createLeg(currentStation, to, 'ZONAL HUB ➔ DESTINATION WOREDA (ከዞን ወደ መዳረሻ ወረዳ)');
      }
    }
  }

  const totalEstimatedHours = parseFloat(legs.reduce((acc, l) => acc + l.estDurationHours, 0).toFixed(1));
  const totalEstimatedFareETB = legs.reduce((acc, l) => acc + l.estFareETB, 0);
  const totalTransfers = Math.max(0, legs.length - 1);

  return {
    origin: from,
    destination: to,
    transferLegs: legs,
    totalEstimatedHours,
    totalEstimatedFareETB,
    totalTransfers,
  };
};
